import { chromium } from 'playwright';
const errors = [];
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', e => errors.push('PAGEERROR: ' + e.message));
await page.goto('http://localhost:5173/#/dashboard', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
console.log('=== BODY TEXT (1280px) ===');
console.log(await page.innerText('body'));
console.log('=== BADGE COUNT "Most overdue" ===');
console.log(await page.locator('text=Most overdue').count());
await page.setViewportSize({ width: 360, height: 800 });
await page.waitForTimeout(300);
console.log('=== scrollWidth at 360 ===');
console.log(await page.evaluate(() => document.documentElement.scrollWidth));
console.log('=== CONSOLE ERRORS ===');
console.log(JSON.stringify(errors));
await browser.close();
